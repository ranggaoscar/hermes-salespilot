UNSUBSCRIBE_WORDS = (
    "unsubscribe", "berhenti kirim", "stop email", "stop mengirim", "hapus saya",
    "remove me", "don't contact", "do not contact", "jangan hubungi", "tidak ingin dihubungi",
    "opt out", "opt-out",
)
NEGATIVE_WORDS = (
    "not interested", "tidak tertarik", "tidak berminat", "no thanks", "no thank you",
    "sudah punya supplier", "already have a supplier", "no stock needed",
)
POSITIVE_WORDS = (
    "interested", "tertarik", "berminat", "kirim penawaran", "send quote", "send quotation",
    "price list", "pricelist", "harga", "quotation", "meeting", "call me", "boleh kirim",
    "minta katalog", "catalog", "sample", "sampel", "budget",
)
_QUOTE_MARKERS = (
    re.compile(r"^-{2,}\s*original message", re.I),
    re.compile(r"^on .+ wrote:$", re.I),
    re.compile(r"^pada .+ menulis:$", re.I),
    re.compile(r"^from:\s", re.I),
)
_AUTO_SUBJECT = re.compile(
    r"^(auto[\s-]?reply|automatic reply|out of (the )?office|ooo\b|abwesenheit|autoreply|"
    r"vacation|balasan otomatis|sedang tidak di kantor)",
    re.I,
)
_BOUNCE_SUBJECT = re.compile(
    r"(undeliver|delivery status|delivery has failed|failure notice|mail delivery|"
    r"returned mail|non[- ]?remis|tidak terkirim)",
    re.I,
)


def _text(value: str | None) -> str:
    if not value:
        return ""
    try:
        return str(make_header(decode_header(value)))
    except Exception:
        return str(value)


def strip_quoted(body: str) -> str:
    lines: list[str] = []
    for line in str(body or "").splitlines():
        if any(marker.match(line.strip()) for marker in _QUOTE_MARKERS):
            break
        if line.lstrip().startswith(">"):
            continue
        lines.append(line)
    return "\n".join(lines).strip()


def parse_message(raw: bytes) -> dict[str, Any]:
    message = email.message_from_bytes(raw)
    body = ""
    if message.is_multipart():
        for part in message.walk():
            if part.get_content_type() == "text/plain" and "attachment" not in str(part.get("Content-Disposition", "")):
                payload = part.get_payload(decode=True) or b""
                body = payload.decode(part.get_content_charset() or "utf-8", "replace")
                break
    else:
        payload = message.get_payload(decode=True) or b""
        body = payload.decode(message.get_content_charset() or "utf-8", "replace")
    clean = strip_quoted(body)[:2000]
    references = message.get_all("References") or []
    refs: list[str] = []
    for item in references:
        refs.extend(str(item).split())
    in_reply_to = str(message.get("In-Reply-To") or "").strip()
    if in_reply_to:
        refs.append(in_reply_to)
    sender = parseaddr(_text(message.get("From")))[1].strip().lower()
    received = ""
    if message.get("Date"):
        try:
            received = parsedate_to_datetime(message["Date"]).astimezone().isoformat(timespec="seconds")
        except Exception:
            received = ""
    return {
        "message_id": str(message.get("Message-ID") or "").strip(),
        "in_reply_to": in_reply_to,
        "references": [item for item in refs if item],
        "subject": _text(message.get("Subject")),
        "sender": sender,
        "recipient": parseaddr(_text(message.get("To")))[1].strip().lower(),
        "received_at": received or domain.iso(),
        "body": clean,
        "body_sha256": hashlib.sha256((clean or body).encode("utf-8", "replace")).hexdigest(),
        "headers": {key.lower(): _text(value) for key, value in message.items()},
    }


def classify_kind(parsed: dict[str, Any]) -> str:
    """auto_reply | bounce | human. Machine mail must never move a prospect to replied."""
    headers = parsed.get("headers") or {}
    auto_submitted = str(headers.get("auto-submitted") or "").strip().lower()
    if auto_submitted and auto_submitted != "no":
        return "auto_reply"
    if headers.get("x-autoreply") or headers.get("x-autorespond") or headers.get("x-autogenerated"):
        return "auto_reply"
    if str(headers.get("precedence") or "").strip().lower() in {"bulk", "auto_reply", "junk"}:
        return "auto_reply"
    content_type = str(headers.get("content-type") or "").lower()
    if "multipart/report" in content_type or "message/delivery-status" in content_type:
        return "bounce"
    if headers.get("x-failed-recipients"):
        return "bounce"
    sender = str(parsed.get("sender") or "").lower()
    if sender.startswith(("mailer-daemon@", "postmaster@")):
        return "bounce"
    subject = str(parsed.get("subject") or "")
    if _BOUNCE_SUBJECT.search(subject):
        return "bounce"
    if _AUTO_SUBJECT.search(subject) or headers.get("x-auto-response-suppress"):
        return "auto_reply"
    return "human"


def classify(text: str) -> str:
    """Evidence-based intent. Every value maps to a status the operator can audit."""
    lowered = str(text or "").lower()
    if any(word in lowered for word in UNSUBSCRIBE_WORDS):
        return "unsubscribe"
    if any(word in lowered for word in NEGATIVE_WORDS):
        return "not_interested"
    if any(word in lowered for word in POSITIVE_WORDS):
        return "interested"
    return "neutral"


def account_addresses(conn, business_id: str) -> set[str]:
    rows = conn.execute(
        "SELECT address_key FROM accounts WHERE business_id=? AND status='active'",
        (business_id,),
    ).fetchall()
    return {str(row["address_key"]).lower() for row in rows}


def find_lead_for(conn, business_id: str, parsed: dict[str, Any],
                  mailbox: set[str] | None = None) -> tuple[str, str, str]:
    """Return (lead_id, match_reason, review_reason). A review reason means a human must look."""
    mailbox = mailbox if mailbox is not None else account_addresses(conn, business_id)
    thread_leads: list[str] = []
    for candidate in [parsed.get("in_reply_to"), *reversed(parsed.get("references") or [])]:
        if not candidate:
            continue
        row = conn.execute(
            "SELECT lead_id FROM messages WHERE business_id=? AND message_id=? AND direction='outbound' LIMIT 1",
            (business_id, candidate),
        ).fetchone()
        if row and row["lead_id"] and row["lead_id"] not in thread_leads:
            thread_leads.append(str(row["lead_id"]))
    if len(thread_leads) == 1:
        return thread_leads[0], "thread", ""
    if len(thread_leads) > 1:
        return "", "", "ambiguous_thread"

    sender = str(parsed.get("sender") or "").lower()
    recipient = str(parsed.get("recipient") or "").lower()
    if not sender:
        return "", "", "missing_sender"
    if mailbox and recipient not in mailbox:
        return "", "", "recipient_not_mailbox"
    rows = conn.execute(
        "SELECT id FROM leads WHERE business_id=? AND lower(email)=? AND deleted_at='' LIMIT 5",
        (business_id, sender),
    ).fetchall()
    if len(rows) == 1:
        return str(rows[0]["id"]), "sender", ""
    if len(rows) > 1:
        return "", "", "ambiguous_sender"
    return "", "", "unknown_sender"


def record_message(conn, business_id: str, parsed: dict[str, Any], *, direction: str, lead_id: str = "",
                  account_id: str = "", delivery_state: str = "unknown", evidence_level: str = "imap_verified",
                  intent: str = "") -> dict[str, Any] | None:
    """Idempotent on (brand, message_id, direction). A message already stored is not rewritten."""
    message_id = str(parsed.get("message_id") or "")
    if message_id:
        existing = conn.execute(
            "SELECT * FROM messages WHERE business_id=? AND message_id=? AND direction=?",
            (business_id, message_id, direction),
        ).fetchone()
        if existing is not None:
            return None
    row_id = domain.new_id("msg")
    conn.execute(
        """INSERT INTO messages(id, business_id, account_id, lead_id, channel, direction, message_id,
           in_reply_to, references_json, subject, sender, recipient, sent_at, received_at, delivery_state,
           evidence_level, intent, body_excerpt, body_sha256, created_at)
           VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            row_id, business_id, account_id, lead_id, "email", direction, message_id,
            str(parsed.get("in_reply_to") or ""), json.dumps(parsed.get("references") or []),
            str(parsed.get("subject") or ""), str(parsed.get("sender") or ""),
            str(parsed.get("recipient") or ""),
            str(parsed.get("sent_at") or ""), str(parsed.get("received_at") or ""),
            delivery_state, evidence_level, intent,
            str(parsed.get("body") or "")[:1000], str(parsed.get("body_sha256") or ""), domain.iso(),
        ),
    )
    return {"id": row_id, "message_id": message_id, "direction": direction, "evidence_level": evidence_level}


def apply_reply(conn, business_id: str, lead_id: str, parsed: dict[str, Any], *, account_id: str = "") -> dict[str, Any]:
    """Store the inbound message, then move the lifecycle only for a human reply."""
    kind = classify_kind(parsed)
    intent = kind if kind != "human" else classify(parsed.get("body") or "")
    stored = record_message(
        conn, business_id, parsed,
        direction="inbound", lead_id=lead_id, account_id=account_id,
        delivery_state="received", evidence_level="imap_verified", intent=intent,
    )
    lead = storage.get_lead(conn, lead_id)
    if lead is None:
        return {"ok": False, "code": "missing_lead", "sent": False}

    if kind == "bounce":
        marker = str(parsed.get("in_reply_to") or "").strip()
        if marker:
            conn.execute(
                "UPDATE messages SET delivery_state='bounced' WHERE business_id=? AND message_id=? AND direction='outbound'",
                (business_id, marker),
            )
        storage.add_event(conn, "bounce_observed", business_id, lead_id,
                          {"message_id": parsed.get("message_id"), "subject": str(parsed.get("subject") or "")[:120]})
        return {"ok": True, "stored": stored is not None, "duplicate": stored is None, "kind": kind,
                "intent": intent, "status": lead.get("pipeline_status") or "",
                "lifecycle_unchanged": True, "sent": False, "prospect": pipeline.public_row(lead)}

    if kind == "auto_reply":
        storage.add_event(conn, "auto_reply_observed", business_id, lead_id,
                          {"message_id": parsed.get("message_id"), "subject": str(parsed.get("subject") or "")[:120]})
        return {"ok": True, "stored": stored is not None, "duplicate": stored is None, "kind": kind,
                "intent": intent, "status": lead.get("pipeline_status") or "",
                "lifecycle_unchanged": True, "sent": False, "prospect": pipeline.public_row(lead)}

    excerpt = (parsed.get("body") or "").strip().splitlines()[0][:240] if parsed.get("body") else ""
    fields: dict[str, Any] = {
        "replied_at": parsed.get("received_at") or domain.iso(),
        "last_inbound_excerpt": excerpt,
        "needs_human": 1 if intent == "interested" else 0,
    }
    status = "replied"
    if intent == "not_interested":
        status = "not_interested"
    elif intent == "unsubscribe":
        status = "do_not_contact"
    fields["pipeline_status"] = status
    storage.set_pipeline_fields(conn, lead_id, **fields)
    # An explicit refusal is permanent consent data; an ambiguous or "later" reply is not. Neutral
    # replies only open a review item, so timing-later wording never suppresses the address.
    if intent == "unsubscribe" and lead.get("email"):
        storage.add_suppression(conn, business_id, lead["email"], "unsubscribe")
    elif intent == "not_interested" and lead.get("email"):
        storage.add_suppression(conn, business_id, lead["email"], "not_interested")
    if intent == "neutral":
        # A human wrote back but the intent is not decidable from the quoted text.
        storage.add_review(conn, business_id, "uncertain_intent", {
            "message_id": parsed.get("message_id"), "sender": parsed.get("sender"),
            "recipient": parsed.get("recipient"), "subject": parsed.get("subject"),
            "received_at": parsed.get("received_at"), "body": str(parsed.get("body") or "")[:500],
            "kind": "human", "lead_id": lead_id, "intent": intent,
        }, account_id=account_id)
    stopped = conn.execute(
        "UPDATE followups SET status='stopped' WHERE business_id=? AND lead_id=? AND status IN ('recommended','scheduled')",
        (business_id, lead_id),
    ).rowcount
    storage.add_event(conn, "reply_observed", business_id, lead_id, {
        "message_id": parsed.get("message_id"), "intent": intent, "status": status,
        "evidence_level": "imap_verified", "followups_stopped": stopped,
    })
    saved = storage.get_lead(conn, lead_id)
    return {
        "ok": True,
        "stored": stored is not None,
        "duplicate": stored is None,
        "kind": kind,
        "intent": intent,
        "status": status,
        "followups_stopped": stopped,
        "prospect": pipeline.public_row(saved or lead),
        "sent": False,
    }


def next_cursor(previous_uidvalidity: str, previous_last_uid: int, server_uidvalidity: str,
                fetched_uids: list[int]) -> dict[str, Any]:
    """A UIDVALIDITY change means the mailbox was rebuilt: start over instead of skipping mail."""
    resync = bool(previous_uidvalidity) and str(server_uidvalidity) != str(previous_uidvalidity)
    highest = max(fetched_uids) if fetched_uids else int(previous_last_uid or 0)
    return {
        "resync": resync,
        "uidvalidity": str(server_uidvalidity or previous_uidvalidity or ""),
        "last_uid": 0 if resync else int(highest),
    }


class ImapFetcher:
    """Real IMAP reader. Credentials are passed per call and never stored."""

    def __init__(self, host: str, port: int, username: str, password: str, *, use_ssl: bool = True):
        self.host = host
        self.port = int(port)
        self.username = username
        self.password = password
        self.use_ssl = use_ssl

    def _client(self):
        return imaplib.IMAP4_SSL(self.host, self.port) if self.use_ssl else imaplib.IMAP4(self.host, self.port)

    def fetch_incremental(self, *, uidvalidity: str = "", last_uid: int = 0, days: int = 30) -> dict[str, Any]:
        client = self._client()
        try:
            client.login(self.username, self.password)
            client.select("INBOX", readonly=True)
            server_uidvalidity = ""
            typ, data = client.response("UIDVALIDITY")
            if typ == "UIDVALIDITY" and data and data[0]:
                server_uidvalidity = data[0].decode() if isinstance(data[0], bytes) else str(data[0])
            start = 1 if (uidvalidity and str(server_uidvalidity) != str(uidvalidity)) else int(last_uid or 0) + 1
            typ, data = client.uid("SEARCH", None, f"UID {start}:*")
            uids = [int(item) for item in (data[0] or b"").split()] if typ == "OK" and data else []
            messages: list[bytes] = []
            for uid in uids:
                typ, payload = client.uid("FETCH", str(uid), "(RFC822)")
                if typ == "OK" and payload and isinstance(payload[0], tuple):
                    messages.append(payload[0][1])
            return {"messages": messages, "uidvalidity": server_uidvalidity, "uids": uids, "start": start}
        finally:
            try:
                client.logout()
            except Exception:
                pass

    def search_recent(self, days: int = 30) -> list[bytes]:
        """First sync when no cursor exists yet."""
        client = self._client()
        try:
            client.login(self.username, self.password)
            client.select("INBOX", readonly=True)
            typ, data = client.search(None, f'(SINCE {_since(days)})')
            if typ != "OK":
                return []
            raws: list[bytes] = []
            for num in (data[0] or b"").split():
                typ, payload = client.fetch(num, "(RFC822)")
                if typ == "OK" and payload and payload[0]:
                    raws.append(payload[0][1])
            return raws
        finally:
            try:
                client.logout()
            except Exception:
                pass


def _since(days: int) -> str:
    from datetime import datetime, timedelta
    return (datetime.now() - timedelta(days=max(1, int(days)))).strftime("%d-%b-%Y")


def sync(conn, business_id: str, raw_messages: Iterable[bytes], *, account_id: str = "") -> dict[str, Any]:
    """Match and store replies from already-fetched raw messages. No network here."""
    parsed_all = [parse_message(raw) for raw in raw_messages]
    mailbox = account_addresses(conn, business_id)
    matched, review, duplicates = [], [], []
    for parsed in parsed_all:
        lead_id, reason, review_reason = find_lead_for(conn, business_id, parsed, mailbox)
        if not lead_id:
            review_id = storage.add_review(conn, business_id, review_reason, {
                "message_id": parsed.get("message_id"), "sender": parsed.get("sender"),
                "recipient": parsed.get("recipient"), "subject": parsed.get("subject"),
                "received_at": parsed.get("received_at"), "body": str(parsed.get("body") or "")[:500],
                "kind": classify_kind(parsed),
            }, account_id=account_id)
            review.append({"reason": review_reason, "sender": parsed.get("sender"), "review_id": review_id})
            continue
        result = apply_reply(conn, business_id, lead_id, parsed, account_id=account_id)
        if result.get("stored"):
            matched.append({"lead_id": lead_id, "match": reason, "kind": result.get("kind", "human"),
                            "intent": result["intent"], "status": result["status"],
                            "lifecycle_unchanged": bool(result.get("lifecycle_unchanged"))})
        else:
            duplicates.append({"lead_id": lead_id, "message_id": parsed.get("message_id")})
    return {
        "ok": True,
        "fetched": len(parsed_all),
        "matched": matched,
        "review": review,
        "unmatched": review,
        "duplicates": duplicates,
        "sent": False,
    }


def run(conn, business_id: str, args: dict[str, Any]) -> dict[str, Any]:
    """Tool/UI entry point. Network only happens on an explicit sync with saved IMAP settings."""
    try:
        from . import plugin_settings
    except ImportError:
        import plugin_settings

    action = str(args.get("action") or "status").strip().lower()
    if action == "preview":
        text = str(args.get("text") or "")
        if not text.strip():
            return {"ok": False, "code": "empty_text", "wrote": False, "sent": False}
        return {"ok": True, "intent": classify(text), "kind": "human", "wrote": False, "sent": False}

    settings = storage.get_imap_settings(conn, business_id)
    configured = bool(settings.get("host") and settings.get("username"))
    username, password, secret_error = plugin_settings.credentials()
    secrets_present = bool(username and password)

    if action == "status":
        account_id = str(args.get("account_id") or "")
        cursor = storage.get_cursor(conn, business_id, account_id) if account_id else {}
        return {
            "ok": True,
            "configured": configured,
            "secrets_present": secrets_present,
            "host": settings.get("host", ""),
            "port": int(settings.get("port") or 993),
            "last_sync_at": settings.get("last_sync_at", ""),
            "cursor": cursor,
            "review_count": len(storage.list_review(conn, business_id)),
            "imap_verified_only": True,
            "one_mailbox_per_secret_slot": True,
            "sent": False,
        }

    if action != "sync":
        return {"ok": False, "code": "bad_action", "error": "Use status, preview, or sync.", "sent": False}

    if not configured:
        return {"ok": False, "code": "imap_not_configured", "error": "Save IMAP settings before syncing.", "sent": False}
    if not secrets_present:
        return {"ok": False, "code": secret_error or "imap_secret_missing", "error": "Mailbox credentials are not in the profile secret scope.", "sent": False}

    account_id = str(args.get("account_id") or "")
    cursor = storage.get_cursor(conn, business_id, account_id)
    days = int(args.get("days") or 30)
    fetcher = ImapFetcher(settings["host"], int(settings.get("port") or 993),
                          str(settings.get("username") or username), password,
                          use_ssl=bool(settings.get("use_ssl", 1)))
    try:
        if cursor.get("uidvalidity") or cursor.get("last_uid"):
            batch = fetcher.fetch_incremental(uidvalidity=cursor["uidvalidity"],
                                              last_uid=int(cursor["last_uid"]), days=days)
            raws = batch["messages"]
            plan = next_cursor(cursor["uidvalidity"], int(cursor["last_uid"]), batch["uidvalidity"], batch["uids"])
        else:
            raws = fetcher.search_recent(days)
            plan = {"resync": False, "uidvalidity": "", "last_uid": 0}
    except Exception as exc:
        return {"ok": False, "code": "imap_failed", "error": type(exc).__name__, "sent": False}
    result = sync(conn, business_id, raws, account_id=account_id)
    if plan["uidvalidity"] or plan["last_uid"]:
        storage.save_cursor(conn, business_id, account_id, plan["uidvalidity"], plan["last_uid"])
    storage.mark_imap_sync(conn, business_id)
    result.update({"days": days, "cursor": plan, "account_id": account_id})
    return result
